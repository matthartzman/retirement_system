def route_allowed(method: str, rule: str) -> bool:
    """True when remote mode serves ``method`` on the registered ``rule``."""
    m = str(method or "GET").upper()
    if m == "HEAD":
        m = "GET"
    if m == "OPTIONS":
        return any((verb, rule) in ALLOWED for verb in ("GET", "POST", "PUT", "PATCH", "DELETE"))
    return (m, rule) in ALLOWED


def refusal_reason(method: str, rule: str) -> str:
    m = "GET" if str(method or "GET").upper() == "HEAD" else str(method or "GET").upper()
    return REFUSED.get((m, rule), "not on the remote-mode allow-list")
